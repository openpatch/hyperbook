import QRCode from "qrcode-svg";
import { useMemo } from "react";
import { cn } from "@/lib/utils";

/** A QR code that scales with its box; black on white so it scans when printed. */
export function QrCode({ value, label, className }: { value: string; label: string; className?: string }) {
  const svg = useMemo(
    () =>
      new QRCode({
        content: value,
        padding: 0,
        ecl: "M",
        join: true,
        xmlDeclaration: false,
        container: "svg-viewbox",
        color: "#000000",
        background: "#ffffff",
      }).svg(),
    [value],
  );
  return (
    <div
      role="img"
      aria-label={label}
      className={cn("aspect-square bg-white [&>svg]:block [&>svg]:size-full", className)}
      // Generated by qrcode-svg from our own login URL; no user markup.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
