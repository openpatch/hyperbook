// Builds the editor completions of the p5 directive from p5's own type
// definitions, so they list exactly what the bundled p5 offers: every global
// function and system variable, and the members of p5.Vector.
//
// Run `pnpm p5:completions` after updating p5.
import fs from "fs";
import path from "path";
// As postbuild.mjs does: p5 does not export its package.json.
const p5Dir = path.join("node_modules", "p5");
const { version } = JSON.parse(
  fs.readFileSync(path.join(p5Dir, "package.json"), "utf8"),
);
const globals = fs.readFileSync(path.join(p5Dir, "types", "global.d.ts"), "utf8");
const types = fs.readFileSync(path.join(p5Dir, "types", "p5.d.ts"), "utf8");

/**
 * The first sentence of a JSDoc comment, as plain text: links and tags
 * reduced to their text, so it fits the completion's info box.
 */
const describe = (jsdoc) => {
  if (!jsdoc) return "";
  const text = jsdoc
    .replace(/^\/\*\*|\*\/$/g, "")
    .split("\n")
    .map((line) => line.replace(/^\s*\* ?/, ""))
    .join("\n")
    .split(/\n\s*@/)[0]
    .split(/\n\s*\n/)[0]
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();
  const sentence = /^.*?[.!?](?=\s|$)/.exec(text)?.[0] ?? text;
  return sentence.length > 200 ? `${sentence.slice(0, 197)}…` : sentence;
};

/** Splits a parameter list at the commas that separate parameters. */
const splitParams = (list) => {
  const params = [];
  let depth = 0;
  let current = "";
  for (const char of list) {
    if ("([{<".includes(char)) depth++;
    if (")]}>".includes(char)) depth--;
    if (char === "," && depth === 0) {
      params.push(current);
      current = "";
    } else {
      current += char;
    }
  }
  if (current.trim()) params.push(current);
  return params.map((param) => param.trim());
};

/** `createCanvas(width?: number, …): X` → `createCanvas(width?, …)` */
const signature = (name, params) =>
  `${name}(${splitParams(params)
    .map((param) => /^(\.\.\.)?\w+\??/.exec(param)?.[0] ?? param)
    .join(", ")})`;

/** The JSDoc comment that ends right before `index`, if any. */
const jsdocBefore = (source, index) => {
  const before = source.slice(0, index).trimEnd();
  if (!before.endsWith("*/")) return "";
  return before.slice(before.lastIndexOf("/**"));
};

/**
 * The parameter list of a declaration that starts at `index` with
 * `name(`: everything up to the matching parenthesis.
 */
const paramsAt = (source, open) => {
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if (source[i] === "(") depth++;
    if (source[i] === ")" && --depth === 0) return source.slice(open + 1, i);
  }
  return "";
};

const entries = new Map();

// Global functions: `function name(…): …;`, one line per overload. The first
// overload carries the documentation.
for (const match of globals.matchAll(/^function (\w+)\(/gm)) {
  const name = match[1];
  if (entries.has(name)) continue;
  const params = paramsAt(globals, match.index + match[0].length - 1);
  entries.set(name, [
    name,
    signature(name, params),
    describe(jsdocBefore(globals, match.index)),
    "function",
  ]);
}

// System variables and constants, documented where p5 adds them to Window:
// `mouseX: typeof P5.mouseX;`. A name in capitals is a constant.
for (const match of globals.matchAll(/^(\w+): typeof P5\.\w+;/gm)) {
  const name = match[1];
  if (entries.has(name)) continue;
  entries.set(name, [
    name,
    name,
    describe(jsdocBefore(globals, match.index)),
    /^[A-Z0-9_]+$/.test(name) ? "constant" : "variable",
  ]);
}

// p5.Vector's instance members, for `v.` after `v = createVector(…)`.
const vectorStart = types.indexOf("  class Vector {");
const vectorEnd = types.indexOf("\n  }\n", vectorStart);
const vectorBody = types.slice(vectorStart, vectorEnd);
const vector = new Map();
// Members are indented by two or four spaces; `static` ones do not match.
for (const match of vectorBody.matchAll(/^ {2,4}(?:readonly )?(\w+)(\??)([(:])/gm)) {
  const [, name, , kind] = match;
  if (name === "constructor" || vector.has(name)) continue;
  const at = vectorStart + match.index;
  vector.set(name, [
    name,
    kind === "("
      ? signature(name, paramsAt(types, at + match[0].length - 1))
      : name,
    describe(jsdocBefore(types, at)),
    kind === "(" ? "method" : "property",
  ]);
}

const byName = (a, b) => a[0].localeCompare(b[0]);
const out = `// Generated by updateP5Completions.mjs from the type definitions of
// p5 ${version}. Run \`pnpm p5:completions\` to refresh; do not edit.
//
// Entries are [name, signature, description, type].

export const P5_VERSION = ${JSON.stringify(version)};

export const P5_GLOBALS = ${JSON.stringify([...entries.values()].sort(byName), null, 0).replace(/\],\[/g, "],\n  [").replace(/^\[\[/, "[\n  [").replace(/\]\]$/, "],\n]")};

export const P5_VECTOR = ${JSON.stringify([...vector.values()].sort(byName), null, 0).replace(/\],\[/g, "],\n  [").replace(/^\[\[/, "[\n  [").replace(/\]\]$/, "],\n]")};
`;

const target = path.join("assets", "directive-p5", "src", "p5-api.js");
fs.writeFileSync(target, out);
console.log(
  `Wrote ${entries.size} globals and ${vector.size} p5.Vector members of p5 ${version} → ${target}`,
);
